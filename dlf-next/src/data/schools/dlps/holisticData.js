export const getDlpsCardPhoto = (subKey, title, idx) => {
  const t = (title || "").toLowerCase();
  const prefix = "/images/dlps/student-life";

  // Visual Arts
  if (t.includes("sketching") || t.includes("pencil")) {
    return { src: `${prefix}/visual-arts/sketching.jpg`, caption: "Sketching & Pencil Shading Studio" };
  }
  if (t.includes("canvas") || t.includes("watercolor")) {
    return { src: `${prefix}/visual-arts/canvas-painting.jpg`, caption: "Canvas Painting & Watercolors" };
  }
  if (t.includes("clay") || t.includes("pottery")) {
    return { src: `${prefix}/visual-arts/clay-modelling.jpg`, caption: "Clay Modeling & Pottery" };
  }
  if (t.includes("sculpture")) {
    return { src: `${prefix}/visual-arts/sculpture.jpg`, caption: "Sculpture & 3D Form Studio" };
  }
  if (t.includes("digital") || t.includes("graphic")) {
    return { src: `${prefix}/visual-arts/digital-design.jpg`, caption: "Digital Design & Graphic Art" };
  }
  if (t.includes("craft") || t.includes("mixed media")) {
    return { src: `${prefix}/visual-arts/craft-design.jpg`, caption: "Craft & Design Studio" };
  }

  // Performing Arts
  if (t.includes("dance")) {
    return { src: `${prefix}/performing-arts/dance.jpg`, caption: "Dance Academy" };
  }
  if (t.includes("vocal")) {
    return { src: `${prefix}/performing-arts/vocal-music.jpg`, caption: "Vocal Music Choir" };
  }
  if (t.includes("instrumental")) {
    return { src: `${prefix}/performing-arts/instrumental-music.jpg`, caption: "Instrumental Music Suite" };
  }
  if (t.includes("theatre") || t.includes("drama")) {
    return { src: `${prefix}/performing-arts/theatre-drama.jpg`, caption: "Theatre & Drama Studio" };
  }
  if (t.includes("stagecraft") || t.includes("performance art") || t.includes("public speaking") || t.includes("speaking")) {
    return { src: `${prefix}/performing-arts/stagecraft.jpg`, caption: "Auditorium Stagecraft & Performance" };
  }

  // Sports Development
  if (t.includes("football") || t.includes("turf")) {
    return { src: `${prefix}/sports/football-turf.jpg`, caption: "Synthetic Football Turf Arena" };
  }
  if (t.includes("skating") || t.includes("rink")) {
    return { src: `${prefix}/sports/skating.jpg`, caption: "Olympic-Size Skating Rink" };
  }
  if (t.includes("swimming") || t.includes("pool")) {
    return { src: `${prefix}/sports/swimming-pool.jpg`, caption: "Two Swimming Pools Arena" };
  }
  if (t.includes("pickleball")) {
    return { src: `${prefix}/sports/pickleball.jpg`, caption: "Exclusive Pickleball Court" };
  }
  if (t.includes("badminton") || t.includes("basketball")) {
    return { src: `${prefix}/sports/badminton.jpg`, caption: "Indoor Basketball & Badminton Courts" };
  }
  if (t.includes("tennis") || t.includes("volleyball")) {
    return { src: `${prefix}/sports/tennis.jpg`, caption: "Lawn Tennis Courts & Volleyball Arena" };
  }

  // Scholastic
  if (t.includes("thot")) {
    return { src: `${prefix}/scholastic/thots-lab.jpg`, caption: "THOTS Cognitive Lab" };
  }
  if (t.includes("innovation") || t.includes("fim")) {
    return { src: `${prefix}/scholastic/innovation-hub.jpg`, caption: "Innovation Hub & FIM Lab" };
  }
  if (t.includes("science") || t.includes("steam")) {
    return { src: `${prefix}/scholastic/science-labs.jpg`, caption: "Advanced Science Laboratories" };
  }
  if (t.includes("ict") || t.includes("computer")) {
    return { src: `${prefix}/scholastic/ict-computer-lab.jpg`, caption: "ICT & Computer Labs" };
  }
  if (t.includes("library") || t.includes("book")) {
    return { src: `${prefix}/scholastic/library.jpg`, caption: "Central School Library" };
  }
  if (t.includes("auditorium") || t.includes("assembly") || t.includes("seminar") || t.includes("conference")) {
    return { src: `${prefix}/scholastic/auditorium.jpg`, caption: "Auditorium, Seminar & Conference Halls" };
  }
  if (t.includes("dear") || t.includes("read")) {
    return { src: `${prefix}/scholastic/dear-reading.jpg`, caption: "DEAR Scheduled Period & Reading Corners" };
  }

  // School Excursions
  if (t.includes("heritage") || t.includes("historical")) {
    return { src: `${prefix}/excursions/historical-heritage.jpg`, caption: "Historical & Heritage Walks" };
  }
  if (t.includes("institutional")) {
    return { src: `${prefix}/excursions/institutional-visits.jpg`, caption: "Institutional Visits" };
  }
  if (t.includes("ecological") || t.includes("environmental")) {
    return { src: `${prefix}/excursions/ecological-expeditions.jpg`, caption: "Ecological Expeditions" };
  }
  if (t.includes("adventure") || t.includes("camp")) {
    return { src: `${prefix}/excursions/adventure-camping.jpg`, caption: "Adventure & Leadership Camps" };
  }
  if (t.includes("global") || t.includes("exchange") || t.includes("tour")) {
    return { src: `${prefix}/excursions/global-tours.jpg`, caption: "Global Educational Tours" };
  }

  return dlpsSubsectionPhotos[subKey]?.[idx % (dlpsSubsectionPhotos[subKey]?.length || 1)] || {
    src: dlpsCategoryThumbnails[subKey],
    caption: title,
  };
};
