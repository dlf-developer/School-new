export const getDlwsCardPhoto = (subKey, title, idx) => {
  const t = (title || "").toLowerCase();
  const prefix = "/images/dlws/student-life";

  // Visual Arts
  if (t.includes("art & design")) {
    return { src: `${prefix}/visual-arts/art-design-studio.jpg`, caption: "Art & Design Studio" };
  }
  if (t.includes("clay") || t.includes("pottery") || t.includes("sculpting")) {
    return { src: `${prefix}/visual-arts/clay-modelling.jpg`, caption: "Clay Modeling & Sculpting" };
  }
  if (t.includes("craft") || t.includes("mixed media") || t.includes("sculpture")) {
    return { src: `${prefix}/visual-arts/mixed-media-craft.jpg`, caption: "Mixed Media & Craft Studio" };
  }
  if (t.includes("digital") || t.includes("graphic")) {
    return { src: `${prefix}/visual-arts/digital-graphic-design.jpg`, caption: "Digital Graphic Design" };
  }

  // Performing Arts
  if (t.includes("dance") || t.includes("movement")) {
    return { src: `${prefix}/performing-arts/dance.jpg`, caption: "Dance & Movement Studio" };
  }
  if (t.includes("vocal")) {
    return { src: `${prefix}/performing-arts/vocal-music.jpg`, caption: "Vocal Music Training" };
  }
  if (t.includes("instrumental")) {
    return { src: `${prefix}/performing-arts/instrumental-music.jpg`, caption: "Instrumental Music Suite" };
  }
  if (t.includes("stagecraft") || t.includes("theatre") || t.includes("drama") || t.includes("public speaking") || t.includes("speaking")) {
    return { src: `${prefix}/performing-arts/stagecraft.jpg`, caption: "Stagecraft & Public Speaking" };
  }

  // Sports Development
  if (t.includes("football") || t.includes("turf")) {
    return { src: `${prefix}/sports/football-turf.jpg`, caption: "Synthetic Football Turf Arena" };
  }
  if (t.includes("skating") || t.includes("rink")) {
    return { src: `${prefix}/sports/skating.jpg`, caption: "Olympic-Size Skating Rink" };
  }
  if (t.includes("pickleball")) {
    return { src: `${prefix}/sports/pickleball.jpg`, caption: "Exclusive Pickleball Court" };
  }
  if (t.includes("tennis") || t.includes("volleyball")) {
    return { src: `${prefix}/sports/tennis.jpg`, caption: "Lawn Tennis Court & Outdoor Arena" };
  }
  if (t.includes("discovery den") || t.includes("kindergarten")) {
    return { src: `${prefix}/sports/discovery-den.jpg`, caption: "Discovery Den Indoor Play Zone" };
  }

  // Scholastic
  if (t.includes("thot") || t.includes("mindspark")) {
    return { src: `${prefix}/scholastic/thots-lab.jpg`, caption: "THOTS & Mindspark Labs" };
  }
  if (t.includes("steam") || t.includes("science")) {
    return { src: `${prefix}/scholastic/steam-lab.jpg`, caption: "STEAM & Science Laboratories" };
  }
  if (t.includes("ict") || t.includes("computer")) {
    return { src: `${prefix}/scholastic/ict-computer-lab.jpg`, caption: "ICT & Computer Labs" };
  }
  if (t.includes("library") || t.includes("book")) {
    return { src: `${prefix}/scholastic/library.jpg`, caption: "3000+ Book Central Library" };
  }

  // School Excursions
  if (t.includes("heritage") || t.includes("historical")) {
    return { src: `${prefix}/excursions/historical-heritage.jpg`, caption: "Historical & Heritage Tours" };
  }
  if (t.includes("institutional")) {
    return { src: `${prefix}/excursions/institutional-visits.jpg`, caption: "Institutional Expeditions" };
  }
  if (t.includes("ecological") || t.includes("environmental")) {
    return { src: `${prefix}/excursions/environmental-outreach.jpg`, caption: "Environmental Outreach" };
  }
  if (t.includes("adventure") || t.includes("camp")) {
    return { src: `${prefix}/excursions/adventure-camping.jpg`, caption: "Adventure & Camping Expeditions" };
  }

  return dlwsSubsectionPhotos[subKey]?.[idx % (dlwsSubsectionPhotos[subKey]?.length || 1)] || {
    src: dlwsCategoryThumbnails[subKey],
    caption: title,
  };
};
